// Converts the SF Symbol outlines exported from the Figma kit (one SVG, one <path id="g_*"> per
// glyph, placed on a grid) into Android vector drawables: res/drawable/sf_<codepoint>_<weight>.xml.
// Run: node tools/svg_to_vector.mjs   (from android/)
import fs from "node:fs";
const svg = fs.readFileSync(new URL("./glyphs_outlined.svg", import.meta.url), "utf8");
const bounds = Object.fromEntries(
  fs.readFileSync(new URL("./glyph_bounds.csv", import.meta.url), "utf8").trim().split("\n")
    .map((l) => l.split(",")).map(([k, x, y, w, h]) => [k, { x: +x, y: +y, w: +w, h: +h }]),
);
const out = new URL("../app/src/main/res/drawable/", import.meta.url);
let n = 0;
for (const m of svg.matchAll(/<path id="g_([^"]+)"([^>]*)\/>/g)) {
  const key = m[1];
  const b = bounds[key];
  if (!b) continue;
  const d = /d="([^"]+)"/.exec(m[2])[1].replace(/-?\d*\.\d+/g, (n) => String(Math.round(parseFloat(n) * 100) / 100));
  const evenOdd = /fill-rule="evenodd"/.test(m[2]);
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/svg_to_vector.mjs from the Figma kit. Tinted at runtime. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${b.w}dp"
    android:height="${b.h}dp"
    android:viewportWidth="${b.w}"
    android:viewportHeight="${b.h}">
    <group android:translateX="${-b.x}" android:translateY="${-b.y}">
        <path
            android:fillColor="#FFFFFFFF"${evenOdd ? '\n            android:fillType="evenOdd"' : ""}
            android:pathData="${d}" />
    </group>
</vector>
`;
  fs.writeFileSync(new URL(`sf_${key}.xml`, out), xml);
  n++;
}
console.log(`wrote ${n} glyphs`);
